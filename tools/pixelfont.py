PX = 100  # font units per pixel; 1 em = 10 pixels
def build(path_woff='questpixel.woff'):
    order = ['.notdef'] + ['u%04X' % ord(c) for c in sorted(G)]
    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap({ord(c): 'u%04X' % ord(c) for c in G})
    glyphs, metrics = {}, {}
    pen = TTGlyphPen(None); pen.moveTo((50, 0)); pen.lineTo((50, 700)); pen.lineTo((450, 700)); pen.lineTo((450, 0)); pen.closePath()
    glyphs['.notdef'] = pen.glyph(); metrics['.notdef'] = (600, 50)
    for c, (rows, top) in G.items():
        width = max(len(r) for r in rows)
        pen = TTGlyphPen(None); xmin = None
        for i, row in enumerate(rows):
            r = i - top                          # row index relative to cap top
            y1 = (7 - r) * PX; y0 = y1 - PX - 2  # 2-unit overlap avoids hairline seams
            x = 0
            while x < len(row):
                if row[x] == '#':
                    s = x
                    while x < len(row) and row[x] == '#': x += 1
                    x0, x1 = s * PX, x * PX
                    pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0)); pen.closePath()
                    xmin = x0 if xmin is None else min(xmin, x0)
                else:
                    x += 1
        name = 'u%04X' % ord(c)
        glyphs[name] = pen.glyph()
        metrics[name] = ((width + 1) * PX, xmin or 0)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=900, descent=-200)
    fb.setupNameTable({'familyName': 'Quest Pixel', 'styleName': 'Regular', 'copyright': 'Original font made for Code Quest. Free to use (MIT).'})
    fb.setupOS2(sTypoAscender=900, sTypoDescender=-200, sTypoLineGap=0, usWinAscent=900, usWinDescent=200, sxHeight=500, sCapHeight=700)
    fb.setupPost()
    fb.font.flavor = 'woff'
    fb.save(path_woff)
    data = open(path_woff, 'rb').read()
    open('questpixel.b64', 'w').write(base64.b64encode(data).decode())
    fb.font.flavor = None; fb.save('questpixel.ttf')
    return len(G), len(data)

if __name__ == '__main__':
    n, size = build()
    print(f'{n} glyphs, woff {size} bytes')
